class TaxAndRevenueEntity01(BaseModel):
    """Operational domain entity 1 for Municipal Taxation & Revenue Audit."""
    model_config = ConfigDict(from_attributes=True, extra='ignore')

    entity_id: str = Field(..., description='Unique identifier for TaxAndRevenueEntity01')
    reference_code: str = Field(..., description='Official municipal reference code')
